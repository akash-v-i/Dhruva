/** English archive terms whose Hindi label appears in the query (for Hindi search). */
export function englishTermsIn(query: string): string[] {
  if (!/[\u0900-\u097f]/.test(query)) return [];
  const out: string[] = [];
  for (const [en, hiText] of Object.entries(translations)) {
    if (en.length <= 40 && hiText.length > 1 && query.includes(hiText)) out.push(en);
  }
  for (const [hiText, en] of Object.entries(searchGlossary)) {
    if (query.includes(hiText)) out.push(en);
  }
  return out;
}

export function uiText(text: string, hindi: boolean): string {
  return hindi ? (translations[text] ?? text) : text;
}
export function contentText(text: string, hindi: boolean): string {
  return uiText(text, hindi);
}
